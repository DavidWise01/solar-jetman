import asyncio,json,re
from pathlib import Path
from playwright.async_api import async_playwright
ROOT=Path(__file__).parent
html=(ROOT/'index.html').read_text()
engine=(ROOT/'engine.mjs').read_text().replace('export const ','const ').replace('export function ','function ')
app=(ROOT/'app.mjs').read_text()
app=re.sub(r'^import .*?;\n','',app,count=1)
bundled=html.replace('<script type="module" src="./app.mjs"></script>', '<script>\n'+engine+'\n'+app+'\n</script>')
checks=[]
def ok(name,b):
 checks.append({'name':name,'pass':bool(b)})
 if not b:print('FAIL',name)
async def run_page(browser,width,height,label):
 page=await browser.new_page(viewport={'width':width,'height':height},device_scale_factor=1)
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 await page.set_content(bundled,wait_until='load')
 await page.wait_for_timeout(180)
 ok(label+' title', 'Möbius' in await page.title())
 ok(label+' A 64', await page.locator('#aMatrix button').count()==64)
 ok(label+' B 64', await page.locator('#bMatrix button').count()==64)
 ok(label+' canvas A', await page.locator('#left').evaluate('(el)=>el.width > 0'))
 ok(label+' canvas B', await page.locator('#right').evaluate('(el)=>el.width > 0'))
 await page.locator('#swap').click()
 await page.wait_for_timeout(160)
 ok(label+' exact bytes ACCEPT',await page.locator('#verdict').inner_text()=='ACCEPT')
 ok(label+' gate receipt 184', (await page.locator('#receipt').inner_text()).find('"gate": 184')>=0)
 await page.locator('#at360').click()
 ok(label+' 360 twist',await page.locator('#twistRead').inner_text()=='REVERSED')
 ok(label+' 360 preserved',await page.locator('#verdict').inner_text()=='ACCEPT')
 ok(label+' B mapped reversed', 'VIEW B[5,5]' in await page.locator('#mapping').inner_text())
 await page.locator('#at720').click()
 ok(label+' 720 orientation reset',await page.locator('#twistRead').inner_text()=='ORIGINAL')
 ok(label+' 720 accepted',await page.locator('#verdict').inner_text()=='ACCEPT')
 await page.locator('#fault').click()
 ok(label+' one-byte tamper REJECT',await page.locator('#verdict').inner_text()=='REJECT')
 await page.locator('#fault').click()
 ok(label+' restore ACCEPT',await page.locator('#verdict').inner_text()=='ACCEPT')
 await page.locator('#cargo').fill('🚀𐌰 / mobius nested data 000')
 ok(label+' cargo changed rejected until reseal',await page.locator('#verdict').inner_text()=='REJECT')
 await page.locator('#swap').click()
 ok(label+' Unicode reseal',await page.locator('#verdict').inner_text()=='ACCEPT')
 await page.locator('#reset').click()
 ok(label+' reset ready',await page.locator('#verdict').inner_text()=='NOT RUN')
 ok(label+' no JS errors',not errors)
 await page.screenshot(path=str(ROOT/(label+'.png')),full_page=True)
 await page.close()
async def main():
 async with async_playwright() as p:
  b=await p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
  await run_page(b,1365,980,'desktop')
  await run_page(b,390,844,'mobile')
  await b.close()
 Path(ROOT/'browser-results.json').write_text(json.dumps({'passed':sum(x['pass'] for x in checks),'total':len(checks),'checks':checks},indent=2))
 print('browser passed',sum(x['pass'] for x in checks),'/',len(checks))
 if not all(x['pass'] for x in checks):raise SystemExit(1)
asyncio.run(main())
